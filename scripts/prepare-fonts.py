"""使用 fonttools + brotli 将原字体无损转为 WOFF2；保留全部字符供编辑器使用。"""
from pathlib import Path
from fontTools.ttLib import TTFont
root=Path(__file__).resolve().parent.parent
out=root/'public/fonts';out.mkdir(parents=True,exist_ok=True)
for source,target in [('GERBIL.OTF','gerbil'),('GEYSTER-DEMO-2.OTF','geyster'),('SourceHanSansCN-Medium.otf','source-han-medium'),('AlibabaPuHuiTi-3-45-Light.ttf','alibaba-light')]:
 output=out/f'{target}.woff2'
 if output.exists() and output.stat().st_mtime >= (root/'fonts'/source).stat().st_mtime:continue
 font=TTFont(root/'fonts'/source);font.flavor='woff2';font.save(output);print(target)
# 页面常用字做小字库；新增文字使用同源完整字库，保持可编辑性。
import json
from fontTools import subset
page=json.loads((root/'content/published/home.json').read_text())
def strings(value):
 if isinstance(value,str):return value
 if isinstance(value,dict):return ''.join(strings(v) for v in value.values())
 if isinstance(value,list):return ''.join(strings(v) for v in value)
 return ''
text=''.join(chr(i) for i in range(32,127))+strings(page)+'设计作品集朱宝玉平面视觉'
text+=''.join(p.read_text() for p in (root/'src/modules').rglob('*.tsx'))
rules=[]
for source,target,family,weight in [('SourceHanSansCN-Medium.otf','source-han-page','SourceHanPage',500),('AlibabaPuHuiTi-3-45-Light.ttf','alibaba-page','AlibabaPage',300)]:
 font=TTFont(root/'fonts'/source)
 subsetter=subset.Subsetter();subsetter.populate(text=text);subsetter.subset(font)
 unicodes=sorted(font.getBestCmap());font.flavor='woff2';font.save(out/f'{target}.woff2')
 ranges=','.join(f'U+{cp:X}' for cp in unicodes)
 rules.append(f"@font-face{{font-family:{family};src:url('/fonts/{target}.woff2') format('woff2');font-weight:{weight};font-display:swap;unicode-range:{ranges}}}")
(root/'src/styles/fonts.generated.css').write_text('/* Generated by scripts/prepare-fonts.py; do not edit. */\n'+'\n'.join(rules)+'\n')
